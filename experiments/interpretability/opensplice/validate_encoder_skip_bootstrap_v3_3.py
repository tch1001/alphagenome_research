def _sha256(path: Path) -> str:
  digest = hashlib.sha256()
  with path.open('rb') as handle:
    for block in iter(lambda: handle.read(1024 * 1024), b''):
      digest.update(block)
  return digest.hexdigest()


def _reject_confirmation_path(path: Path) -> None:
  if any('confirm' in part.lower() for part in path.resolve().parts):
    raise ValueError(f'Confirmation-named path is forbidden: {path}.')


def validate_upstream_checkout(frozen: dict[str, Any]) -> dict[str, Any]:
  """Binds the tracked-clean upstream checkout and its 26 import sources."""
  head = subprocess.check_output(
      ('git', '-C', str(_UPSTREAM), 'rev-parse', 'HEAD'), text=True
  ).strip()
  if head != frozen.get('upstream_alphagenome_git_head'):
    raise ValueError('Upstream AlphaGenome HEAD changed.')
  if subprocess.check_output(
      ('git', '-C', str(_UPSTREAM), 'diff', '--binary', 'HEAD', '--')
  ):
    raise ValueError('Upstream AlphaGenome checkout has tracked edits.')
  inventory = frozen.get('upstream_imported_modules')
  if not isinstance(inventory, dict) or len(inventory) != 26:
    raise ValueError('Frozen upstream import inventory must have 26 modules.')
  exception = frozen.get('upstream_generated_binding_exception')
  if not isinstance(exception, dict) or set(exception) != {
      'module_names', 'generated_outputs', 'source_inputs',
      'embedded_headers', 'protobuf_runtime_version',
      'grpcio_runtime_version', 'grpcio_tools',
      'historical_generator', 'historical_generator_argv',
      'exact_regeneration_claim',
  }:
    raise ValueError('Frozen upstream generated-binding exception changed.')
  if exception != EXPECTED_UPSTREAM_GENERATED_BINDING_EXCEPTION:
    raise ValueError('Upstream generated-binding bytes differ from protocol §2.3.')
  if (
      exception['protobuf_runtime_version']
      != importlib.metadata.version('protobuf')
      or exception['grpcio_runtime_version']
      != importlib.metadata.version('grpcio')
  ):
    raise ValueError('Upstream generated-binding claims changed.')
  try:
    importlib.metadata.version('grpcio-tools')
  except importlib.metadata.PackageNotFoundError:
    pass
  else:
    raise ValueError('grpcio-tools unexpectedly exists in the frozen runtime.')
  for relative, binding in exception['source_inputs'].items():
    if not isinstance(binding, dict) or set(binding) != {
        'sha256', 'size_bytes'
    }:
      raise ValueError(f'Upstream source-input schema changed: {relative}.')
    path = (_UPSTREAM / relative).resolve()
    subprocess.run(
        ('git', '-C', str(_UPSTREAM), 'ls-files', '--error-unmatch', relative),
        check=True,
        capture_output=True,
    )
    if (
        path.is_symlink() or not path.is_file()
        or _sha256(path) != binding['sha256']
        or path.stat().st_size != binding['size_bytes']
    ):
      raise ValueError(f'Upstream generated source input changed: {relative}.')
  records = {}
  for module_name, binding in sorted(inventory.items()):
    if not isinstance(binding, dict) or set(binding) != {
        'relative_path', 'sha256', 'size_bytes'
    }:
      raise ValueError(f'Upstream binding schema changed: {module_name}.')
    relative = binding['relative_path']
    path = (_UPSTREAM / relative).resolve()
    try:
      normalized = str(path.relative_to(_UPSTREAM.resolve()))
    except ValueError as error:
      raise ValueError('Upstream import path escaped checkout.') from error
    if normalized != relative or path.suffix != '.py':
      raise ValueError(f'Upstream import path changed: {module_name}.')
    is_generated = module_name in UPSTREAM_GENERATED_MODULE_NAMES
    tracked = subprocess.run(
        ('git', '-C', str(_UPSTREAM), 'ls-files', '--error-unmatch', relative),
        capture_output=True,
    ).returncode == 0
    if is_generated:
      if tracked or exception['generated_outputs'][module_name] != binding:
        raise ValueError(f'Upstream generated-output contract changed: {module_name}.')
      ignored = subprocess.check_output(
          ('git', '-C', str(_UPSTREAM), 'check-ignore', '-v', relative),
          text=True,
      ).strip()
      if not ignored.endswith(f'**/*pb2*.py\t{relative}'):
        raise ValueError(f'Upstream generated output is not ignored: {module_name}.')
    elif not tracked:
      raise ValueError(f'Upstream source is not tracked: {module_name}.')
    if (
        path.is_symlink() or not path.is_file()
        or _sha256(path) != binding['sha256']
        or path.stat().st_size != binding['size_bytes']
    ):
      raise ValueError(f'Upstream imported source changed: {module_name}.')
    records[module_name] = {
        **binding, 'path': str(path),
        'source_kind': 'generated_exact_byte_exception' if is_generated else 'tracked',
    }
  expected_headers = exception['embedded_headers']
  if exception['embedded_headers'] != expected_headers:
    raise ValueError('Upstream generated embedded-header contract changed.')
  for module_name, expected_lines in expected_headers.items():
    text = (_UPSTREAM / inventory[module_name]['relative_path']).read_text(
        encoding='utf-8'
    )
    if any(line not in text.splitlines() for line in expected_lines):
      raise ValueError(f'Upstream generated header changed: {module_name}.')
  return {
      'git_head': head,
      'tracked_head_clean': True,
      'imported_module_count': len(records),
      'imported_modules': records,
      'tracked_imported_module_count': 22,
      'generated_imported_module_count': 4,
      'generated_binding_exception': exception,
  }


def validate_prior_v3_2_evidence(frozen: dict[str, Any]) -> dict[str, Any]:
  """Validates the exact v3.2 evidence cited by the v3.3 protocol."""
  binding = frozen.get('prior_v3_2_evidence')
  if binding != EXPECTED_PRIOR_V3_2_EVIDENCE:
    raise ValueError('Frozen v3.2 evidence binding differs from protocol §1.')
  for name in ('protocol', 'analysis', 'result'):
    item = binding[name]
    path = Path(item['path']).resolve()
    _reject_confirmation_path(path)
    if _sha256(path) != item['sha256']:
      raise ValueError(f'Prior v3.2 {name} bytes changed.')
  raw_binding = binding['raw_manifest']
  manifest_path = Path(raw_binding['path']).resolve()
  _reject_confirmation_path(manifest_path)
  if _sha256(manifest_path) != raw_binding['sha256']:
    raise ValueError('Prior v3.2 raw manifest bytes changed.')
  manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
  if (
      manifest.get('artifact_count') != raw_binding['artifact_count']
      or manifest.get('artifact_tree_sha256')
      != raw_binding['artifact_tree_sha256']
      or len(manifest.get('artifact_sha256', {}))
      != raw_binding['artifact_count']
  ):
    raise ValueError('Prior v3.2 raw manifest contract changed.')
  run_root = manifest_path.parent
  tree = hashlib.sha256()
  for relative, expected_sha in sorted(manifest['artifact_sha256'].items()):
    path = (run_root / relative).resolve()
    _reject_confirmation_path(path)
    if not path.is_relative_to(run_root) or _sha256(path) != expected_sha:
      raise ValueError(f'Prior v3.2 raw artifact changed: {relative}.')
    tree.update(relative.encode('utf-8'))
    tree.update(b'\0')
    tree.update(bytes.fromhex(expected_sha))
  if tree.hexdigest() != raw_binding['artifact_tree_sha256']:
    raise ValueError('Prior v3.2 raw tree digest changed.')
  return binding


def validate_freeze() -> dict[str, Any]:
  for path in (FREEZE_PATH, PROTOCOL_PATH, SUPERSESSION_PATH):
    _reject_confirmation_path(path)
  if _sha256(PROTOCOL_PATH) != PROTOCOL_SHA256:
    raise ValueError('v3.3 protocol hash changed.')
  if _sha256(SUPERSESSION_PATH) != SUPERSESSION_SHA256:
    raise ValueError('v3.3 supersession hash changed.')
  frozen = json.loads(FREEZE_PATH.read_text(encoding='utf-8'))
  expected = {
      'protocol_sha256': PROTOCOL_SHA256,
      'supersession_sha256': SUPERSESSION_SHA256,
      'supersession_commit': SUPERSESSION_COMMIT,
  }
  for name, value in expected.items():
    if frozen.get(name) != value:
      raise ValueError(f'v3.3 bootstrap freeze mismatch: {name}.')
  tracked = {
      str(FREEZE_PATH.relative_to(_REPO)),
      str(PROTOCOL_PATH.relative_to(_REPO)),
      str(SUPERSESSION_PATH.relative_to(_REPO)),
  }
  for relative, expected_sha in frozen['file_sha256'].items():
    path = (_REPO / relative).resolve()
    try:
      normalized = str(path.relative_to(_REPO))
    except ValueError as error:
      raise ValueError(f'Frozen path escapes repository: {relative}.') from error
    if normalized != relative:
      raise ValueError(f'Frozen path is not normalized: {relative}.')
    _reject_confirmation_path(path)
    if _sha256(path) != expected_sha:
      raise ValueError(f'v3.3 frozen file changed: {relative}.')
    tracked.add(relative)
  for relative in sorted(tracked):
    subprocess.run(
        ('git', '-C', str(_REPO), 'ls-files', '--error-unmatch', relative),
        check=True,
        capture_output=True,
    )
  if subprocess.check_output(
      ('git', '-C', str(_REPO), 'diff', '--binary', 'HEAD', '--')
  ):
    raise ValueError('v3.3 requires globally tracked-clean HEAD before import.')
  upstream = validate_upstream_checkout(frozen)
  prior = validate_prior_v3_2_evidence(frozen)
  return {
      'path': str(FREEZE_PATH.resolve()),
      'sha256': _sha256(FREEZE_PATH),
      'git_head': subprocess.check_output(
          ('git', '-C', str(_REPO), 'rev-parse', 'HEAD'), text=True
      ).strip(),
      'tracked_head_clean': True,
      'tracked_paths': sorted(tracked),
      'upstream_checkout': upstream,
      'prior_v3_2_evidence': prior,
  }


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--check', action='store_true', required=True)
  record = {
      'generated_bindings': proto_gate.validate_generated_bindings_before_import(),
      'freeze': validate_freeze(),
      'model_or_jax_imported': False,
  }
  print(json.dumps(record, indent=2, sort_keys=True))


if __name__ == '__main__':
  main()
